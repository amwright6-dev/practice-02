import math

PI = math.pi

radius = float(input("Enter the radius of the circle: 5.0"))

area = PI * radius ** 2
circumference = 2 * PI * radius

print(f"Area: {area:.2f} 78.54 sqaure units")
print(f"Circumference: {circumference:.2f} 31.42 units")
